export const MAX_SLOTS = 12 // fixed rows shown in the editor
/** Fallback sigil/trait level when no cap is known (mirrors C# DefaultLevel). */
export const DEFAULT_LEVEL = 15
/** Menu hotkey fallback when tool-hotkey.txt is unavailable (F1). */
export const DEFAULT_HIDE_KEY = 0x70

export interface Slot {
  mainHash: string
  /** 载入时存档里那个 gem hash（主下拉的值是组键，只有它能记住选的是组里的哪个变体）。
   * 用户重新选主因子时由 SlotEditor 清空。空 = 没有可保留的变体。 */
  mainGem: string
  mainLevel: number
  secHash: string
  secLevel: number
  enabled: boolean
}

/** One entry of a saved loadout.json slot item list (the file shape).
 * level stays optional: a hand-edited file may omit it (DEFAULT_LEVEL).
 * Older builds also wrote zh/en here; the mod never read them and nothing
 * writes them anymore — names are not part of the data. */
export interface SavedItem {
  gem?: string
  hash?: string
  level?: number
}

export interface Sigil {
  hash: string // gem hash (= item identity; skill entries use the trait hash)
  skill1: string // primary trait hash — the main picker's group key
  player: string
  onlyone?: string // gem.CanOnlyHoldOne: "1" = 唯一持有
  mix?: string // gem.CanGemMix: "0" ordinary (free combination), "1" locked
  cap?: number // trait level cap (row data, feeds the trait dictionary only)
  lot?: string[] // pool versions: legal secondary trait hashes (empty = no pool)
  skill2?: string // fixed-second versions: the fixed secondary trait hash
}

export interface Trait {
  hash: string
  /** 命名这个技能的那一行物品的 hash：显示名按它去 gem.lang.json 里取。 */
  gem: string
  cap: number
}

/** One row of gem.chara.json (generated by tool-gen-loadout.ps1):
 * 每个角色三个专属槽，按槽位顺序存 [因子 hash, 技能 hash] 对。 */
export interface Exclusive {
  hash: string // 角色 hash：loadout.json 里 exclusive 的键就是它（身份）
  player: string // PL 码：面板按它合并"共享同一个码的角色"，也是 chara.lang.json 的键
  gems: [string, string][] // [因子 hash, 技能 hash] ×3
}

/** 一条专属记录的三个槽：写入配置的键 + 屏幕上的名字。
 *
 * 元组按位置读，0 = T1、1 = T2、2 = 战气。两个 hash 各管一头，不能对调：
 * loadout.json 的状态键是**技能** hash（`[1]`），而名字表 gem.lang.json 以
 * **因子物品** hash（`[0]`）为键——取错一个下标，整页标签就退化成裸 hash。
 * 所以这个读法只留在这里，别在组件里再解构一次。 */
export function exclusiveSlots(
  row: Exclusive,
  names: Record<string, string>
): { traitHash: string; label: string }[] {
  return row.gems.map(([gem, skill]) => ({ traitHash: skill, label: names[gem] ?? gem }))
}

/** The trust boundary for gem.chara.json: 形状不完整的记录整条丢掉。非数组直接抛，
 * 交给调用方的错误提示。这张表只有**可视工具**在读（mod 侧不读它：专属开关经 ABI 以
 * 技能 hash 转发，是哪个槽由原生侧认）。 */
export function parseExclusiveTable(raw: unknown): Exclusive[] {
  if (!Array.isArray(raw)) throw new Error("gem.chara.json is not an array")
  return raw.filter(
    (row): row is Exclusive =>
      typeof row?.hash === "string" &&
      typeof row?.player === "string" &&
      Array.isArray(row?.gems) &&
      row.gems.length === 3 &&
      row.gems.every(
        (g: unknown) =>
          Array.isArray(g) && g.length === 2 && g.every((h) => typeof h === "string")
      )
  )
}

/** Exclusive overlay written to loadout.json: 角色 hash -> 技能 hash -> 是否启用。
 * 只有被关掉的槽需要出现——没提到的角色就是三槽全开。 */
export type ExclusiveState = Record<string, Record<string, boolean>>

/** Keys that must never be written into the plain exclusive state object. */
const BLOCKED_KEYS = new Set(["__proto__", "constructor", "prototype"])

/** Sanitize a loaded "exclusive" object: drop prototype keys and non-boolean
 * values so a hand-written file cannot pollute the editor state. */
export function sanitizeExclusiveState(raw: unknown): ExclusiveState | undefined {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return undefined
  const out: ExclusiveState = {}
  for (const [player, value] of Object.entries(raw as Record<string, unknown>)) {
    if (BLOCKED_KEYS.has(player)) continue
    if (!value || typeof value !== "object" || Array.isArray(value)) continue
    const inner: Record<string, boolean> = {}
    for (const [trait, enabled] of Object.entries(value as Record<string, unknown>)) {
      if (BLOCKED_KEYS.has(trait)) continue
      if (typeof enabled === "boolean") inner[trait] = enabled
    }
    out[player] = inner
  }
  return Object.keys(out).length > 0 ? out : undefined
}

const emptySlot = (): Slot => ({
  mainHash: "",
  mainGem: "",
  mainLevel: 0,
  secHash: "",
  secLevel: 0,
  enabled: true,
})

/** Normalize a saved config (new array format) into Slot[].
 *
 * 存档里存的是 gem hash，而下拉的值是**组键**（该行所属的技能 hash，`skill1`），
 * 所以这里把前者翻成后者；表里没有的 gem 保留原值（下一次保存会被丢弃，
 * 编辑里也显示为空）。名字不参与：它按语言变，不能当身份。
 *
 * Levels are clamped to the cap the table knows about so an out-of-range
 * hand-edited value cannot make the mod reject the file. */
export function configToSlots(
  parsed: { slots?: unknown },
  sigils: Sigil[],
  traits: Trait[] = []
): Slot[] {
  const capOfTrait = new Map(traits.map((tr) => [tr.hash, tr.cap]))
  const capOfGem = new Map<string, number | undefined>(
    sigils.map((s) => [s.hash, capOfTrait.get(s.skill1)])
  )
  const fromCfg = slotsFromConfig(parsed?.slots, capOfGem, capOfTrait)
  const mainKeyOfGem = new Map(sigils.map((s) => [s.hash, s.skill1 || s.hash]))
  for (const s of fromCfg) {
    if (mainKeyOfGem.has(s.mainHash)) s.mainHash = mainKeyOfGem.get(s.mainHash) as string
  }
  return fromCfg
}

/** 保存时这个主因子该写成哪个 gem hash（主下拉的值是组键，不是物品）。
 *
 * 顺序即优先级：存档已经指名的那一个变体（preferred，且仍与当前副技能相容）→
 * 池版 → 固定副技能那版 → 组里第一行。第一档是必需的：一个组里可以有**名字不同**的
 * 两个变体（钳蟹的共鸣 / 永恒钳蟹因子），丢了它，没被碰过的那一行也会被静默改写。
 * 固定的副技能不写进 loadout.json（mod 从 gem 自己推），所以它对应的 secHash 是空。 */
export function resolveMainGem(
  variants: Sigil[],
  pool: { poolHash: string; lot: Set<string> } | undefined,
  secHash: string,
  preferred: string
): string {
  if (variants.length === 0) return ""
  const kept = preferred === "" ? undefined : variants.find((v) => v.hash === preferred)
  if (kept && (secHash === "" || kept.skill2 === secHash)) return kept.hash
  if (pool && (secHash === "" || pool.lot.has(secHash))) return pool.poolHash
  const fixed = secHash !== "" ? variants.find((v) => v.skill2 === secHash) : undefined
  return fixed?.hash ?? pool?.poolHash ?? variants[0].hash
}

/** Pad the editor to at least MAX_SLOTS rows so the user just fills them in.
 * Extra rows from an over-long saved config pass through: the Go/C# validators
 * reject them instead of silently truncating (data loss on next autosave). */
export function pad12(slots: Slot[]): Slot[] {
  const out = [...slots]
  while (out.length < MAX_SLOTS) out.push(emptySlot())
  return out
}

/** Clamp a stored level to the table cap when one is known. */
const clampLevel = (level: number, cap: number | undefined) =>
  cap === undefined ? level : Math.max(0, Math.min(level, cap))

/** gem.json 里的一行：物品行 hash != skill1，非物品技能行 hash == skill1。 */
export type SigilRow = Partial<Sigil>

/** gem.json 的 sigils 数组。 */
export function parseSigilRows(json: string): SigilRow[] {
  const parsed = JSON.parse(json) as { sigils?: SigilRow[] }
  return parsed.sigils ?? []
}

/** 技能字典：每个技能 hash 一行（首行胜出），专属行不作副技能候选。 */
export function traitTableOf(rows: SigilRow[]): Trait[] {
  const byHash = new Map<string, Trait>()
  for (const s of rows) {
    if (!s.skill1 || byHash.has(s.skill1)) continue
    if (s.player) continue // 专属因子的技能永不出现在技能下拉里
    byHash.set(s.skill1, {
      hash: s.skill1,
      // 显示名来自命名它那一行的物品名，所以取名字时用那一行的 hash。
      gem: s.hash ?? "",
      cap: s.cap ?? DEFAULT_LEVEL,
    })
  }
  return [...byHash.values()]
}

/** 可选的主因子：只收物品行（非物品技能行不给选）。 */
export function itemRowsOf(rows: SigilRow[]): Sigil[] {
  return rows
    .filter((s) => s.hash !== s.skill1)
    .map((s) => ({
      hash: s.hash ?? "",
      skill1: s.skill1 ?? "",
      player: s.player ?? "",
      onlyone: s.onlyone ?? "",
      mix: s.mix ?? "",
      lot: s.lot?.length ? s.lot : undefined,
      skill2: s.skill2 || undefined,
    }))
}

/** 没有合法副技能时共用的空集合：`legalOf` 每次返回同一个对象，调用方就不必再造一个。 */
const NO_LEGAL_TRAITS: Set<string> = new Set()

/**
 * 一张因子表的**全部**派生关系，构造一次。主/副下拉的取值集合、显示名、等级上限、
 * 合法副集合，以及"这个主因子该写成哪个物品 hash"。
 *
 * 以前这些散在 App.tsx 的 10 个 useMemo + 3 个 useCallback 里，而"合法副技能"与
 * "该写哪个变体"这两个其实同源的关系被各写了一遍。现在只有这一处构造，而且它不需要
 * React 就能被测试。
 */
export interface SigilIndex {
  /** 主下拉的取值：每组的组键（该组变体共享的技能 hash）。 */
  mainKeys: string[]
  mainKeySet: Set<string>
  /** 副下拉的取值：每个技能 hash。 */
  traitHashes: string[]
  /** value -> 当前语言的显示名。取不到名字的键根本不在表里，调用方回落成原值。 */
  labels: Record<string, string>
  /** 合法的副技能集合；参不来（唯一持有/非物品行组）就是一个空集合。 */
  legalOf(mainKey: string): Set<string>
  /** 保存时这个主因子该写成哪个物品 hash（规则见 resolveMainGem）。 */
  gemOf(mainKey: string, secHash?: string, preferred?: string): string
  capOfMain(mainKey: string): number
  capOfTrait(traitHash: string): number
}

export function buildSigilIndex(
  sigils: Sigil[],
  traits: Trait[],
  names: Record<string, string>
): SigilIndex {
  const traitByName = new Map(traits.map((tr) => [tr.hash, tr]))

  // 主因子按技能分组：名字按语言变、不能当键，而同一名字的那些本来也共享一条技能。
  const grouped = new Map<string, Sigil[]>()
  for (const s of sigils) {
    const key = s.skill1 || s.hash
    const group = grouped.get(key)
    if (group) group.push(s)
    else grouped.set(key, [s])
  }

  // 主下拉只收"组里至少有一个非专属行"的组；专属因子由专属页管理。
  const mainKeys = [...grouped.entries()]
    .filter(([, variants]) => variants.some((v) => v.player === ""))
    .map(([key]) => key)

  // 显示名来自命名该技能的那一行物品：技能字典是首行胜出，而 App 建 traits 时已经
  // 剔除了专属行，所以这里一份就够——主下拉的每个键都是某个非专属行的 skill1。
  const labels: Record<string, string> = {}
  for (const tr of traits) labels[tr.hash] = names[tr.gem] ?? tr.hash

  // 池族：池版那一行 + 它声明的合法副列表（lot）。gemOf 用它决定写池版还是固定版。
  const poolOf = new Map<string, { poolHash: string; lot: Set<string> }>()
  for (const [key, variants] of grouped) {
    const pool = variants.find((v) => v.lot && v.lot.length > 0)
    if (pool) poolOf.set(key, { poolHash: pool.hash, lot: new Set(pool.lot) })
  }

  // 能当副技能的技能：至少有一个普通（mix=0、可组合）物品行提供它。
  const ordinary = new Set<string>()
  for (const s of sigils) {
    if (s.onlyone !== "1" && s.hash !== s.skill1 && s.mix === "0") ordinary.add(s.skill1)
  }

  // 组合规则（仅提示：不阻断选择、保存或实装）：
  //   1. 唯一持有 / 非物品行组没有合法副；
  //   2. mix=1 只配自己的池或固定副技能；
  //   3. 其余普通（mix=0）行自由组合。
  const legalOf = (mainKey: string): Set<string> => {
    const variants = (grouped.get(mainKey) ?? []).filter(
      (s) => s.onlyone !== "1" && s.hash !== s.skill1
    )
    if (variants.length === 0) return NO_LEGAL_TRAITS
    if (variants.some((v) => v.mix === "0")) return ordinary
    const legal = new Set<string>()
    for (const v of variants) {
      if (v.mix !== "1") continue
      if (v.skill2 && ordinary.has(v.skill2)) legal.add(v.skill2)
      for (const h of v.lot ?? []) if (ordinary.has(h)) legal.add(h)
    }
    return legal
  }

  const capOfTrait = (traitHash: string): number =>
    traitByName.get(traitHash)?.cap ?? DEFAULT_LEVEL

  const capOfMain = (mainKey: string): number => {
    const variants = grouped.get(mainKey)
    return variants && variants.length > 0 ? capOfTrait(variants[0].skill1) : DEFAULT_LEVEL
  }

  const gemOf = (mainKey: string, secHash = "", preferred = ""): string => {
    const variants = grouped.get(mainKey)
    if (!variants || variants.length === 0) return ""
    return resolveMainGem(variants, poolOf.get(mainKey), secHash, preferred)
  }

  return {
    mainKeys,
    mainKeySet: new Set(mainKeys),
    traitHashes: traits.map((tr) => tr.hash),
    labels,
    legalOf,
    gemOf,
    capOfMain,
    capOfTrait,
  }
}

/** One slot as loadout.json stores it. */
export interface SavedSlot {
  items: SavedItem[]
  enabled: boolean
}

/** loadout.json 的内容。 */
export interface LoadoutPayload {
  lang: string
  slots: SavedSlot[]
  exclusive?: ExclusiveState
}

/**
 * 把编辑器状态拼成落盘载荷。
 *
 * 这段拼装此前**零覆盖**，而它决定了用户配置的内容：主因子按当前表解析成物品 hash、
 * 解析不出就整行跳过（空 id 会让 mod 拒掉整份文件）、副技能有就写没有就不写、
 * exclusive 全空时不写这个成员。抽成纯函数是为了能对真实 gem.json 测它。
 */
export function buildLoadoutPayload(
  slots: Slot[],
  index: SigilIndex,
  lang: string,
  exclusive: ExclusiveState | undefined
): LoadoutPayload {
  const saved: SavedSlot[] = []
  for (const s of slots) {
    if (s.mainHash === "") continue
    const hash = index.gemOf(s.mainHash, s.secHash, s.mainGem)
    if (hash === "") continue
    // items[0] 同时写物品 hash 与它给的主技能：mod 不再持有因子表（那张表的唯一实现就是
    // 本文件建的索引），所以主技能必须随载荷走。
    const items: SavedItem[] = [{ gem: hash, hash: s.mainHash, level: s.mainLevel }]
    if (s.secHash !== "") items.push({ hash: s.secHash, level: s.secLevel })
    saved.push({ items, enabled: s.enabled })
  }
  const trimmed =
    exclusive && Object.keys(exclusive).length > 0 ? exclusive : undefined
  return { lang, slots: saved, exclusive: trimmed }
}

/** The trust boundary for saved configs: untrusted JSON shape -> Slot[].
 * Every field is guarded, so a hand-edited or truncated loadout.json degrades
 * to empty slots instead of throwing. The two cap maps are required - the only
 * caller always has both. */
function slotsFromConfig(
  raw: unknown,
  capOfGem: Map<string, number | undefined>,
  capOfTrait: Map<string, number>
): Slot[] {
  const arr = Array.isArray(raw) ? raw : []
  return arr.map((slot) => {
    const s = (slot ?? {}) as {
      enabled?: boolean
      items?: SavedItem[]
    }
    const items = Array.isArray(s.items) ? s.items : []
    const main = items[0] ?? {}
    const sec = items[1]
    const mainHash = typeof main.gem === "string" ? main.gem : "" // 主技能由 configToSlots 从索引还原
    const secHash = sec && typeof sec.hash === "string" ? sec.hash : ""
    const mainLevel = typeof main.level === "number" ? main.level : DEFAULT_LEVEL
    const secLevel = sec && typeof sec.level === "number" ? sec.level : DEFAULT_LEVEL
    return {
      mainHash,
      // 存档里的 gem hash 原样留着：configToSlots 随后把 mainHash 换成组键，
      // 组里"名字不同的那两个变体"就只能靠这个字段区分（见 hashFor 的 preferred）。
      mainGem: mainHash,
      mainLevel: clampLevel(mainLevel, capOfGem.get(mainHash)),
      secHash,
      secLevel: clampLevel(secLevel, capOfTrait.get(secHash)),
      enabled: s.enabled !== false,
    }
  })
}
